def rule(code: str) -> CraftRule | None:
    """按编号取规则，供检查项标注出处。"""
    for item in CRAFT_RULES:
        if item.code == code:
            return item
    return None


def catalog() -> list[dict[str, str]]:
    """给界面用的规则清单（含出处）。"""
    return [
        {
            "code": item.code,
            "summary": item.summary,
            "source": item.source,
            "advice": item.advice,
            "detail": item.detail,
        }
        for item in CRAFT_RULES
    ]


